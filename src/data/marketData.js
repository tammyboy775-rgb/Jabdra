export function currentSeason(date = new Date()) {
  const m = date.getMonth()
  if (m >= 1 && m <= 3) return 'spring'
  if (m >= 4 && m <= 6) return 'summer'
  if (m >= 7 && m <= 9) return 'autumn'
  return 'winter'
}
